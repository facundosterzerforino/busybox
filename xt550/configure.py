#!/usr/bin/env python
"""Configure busybox for the XT550 without busybox's Linux-only build system.

1. scripts/gen_build_files.sh (POSIX sh) must have run: it makes Kbuild,
   Config.in, include/applets.h and include/usage.h from the sources.
2. This script resolves Kconfig with kconfiglib (pure Python): every applet
   off except APPLETS below, everything else at busybox's defaults, plus the
   overrides for a static Android 2.3 (bionic) binary.
3. It writes .config and include/autoconf.h in busybox's format (CONFIG_X,
   ENABLE_X, IF_X(...), IF_NOT_X(...)), like scripts/kconfig/confdata.c.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kconfiglib

SRC = sys.argv[1]

# Commands used to maintain the phone over adb (root shell has no cp, printf, [ ...)
# Not built: DF (no statvfs in bionic android-9), TOUCH (no utimensat).
APPLETS = """CAT CP MV RM RMDIR LS MKDIR CHMOD CHOWN CHGRP LN READLINK REALPATH
TEST TEST1 TEST2 PRINTF ECHO TRUE FALSE SLEEP USLEEP ENV EXPR SEQ BASENAME DIRNAME
TAR GZIP GUNZIP ZCAT SHA256SUM SHA1SUM MD5SUM SHA512SUM CMP
FIND XARGS STAT AWK SED GREP EGREP FGREP HEAD TAIL WC SORT UNIQ TR CUT TEE OD HEXDUMP STRINGS
DD DU SYNC KILLALL PIDOF PGREP PKILL FREE UPTIME NC WHICH DATE""".split()

OVERRIDES = {
    'STATIC': 'y', 'LFS': 'n',  # bionic android-9: 32-bit off_t only
    'BUSYBOX': 'y', 'SHOW_USAGE': 'y',
    'FEATURE_VERBOSE_USAGE': 'n', 'FEATURE_COMPRESS_USAGE': 'n',
    'FEATURE_INSTALLER': 'n', 'INSTALL_NO_USR': 'n',
    'FEATURE_SUID': 'n', 'FEATURE_SUID_CONFIG': 'n', 'SELINUX': 'n', 'PAM': 'n',
    'FEATURE_UTMP': 'n', 'FEATURE_WTMP': 'n', 'FEATURE_SHADOWPASSWDS': 'n',
    'USE_BB_PWD_GRP': 'n', 'USE_BB_SHADOW': 'n',  # bionic passwd has no pw_gecos
    'USE_BB_CRYPT': 'y',
    'FEATURE_SYSLOG': 'n', 'FEATURE_SYSLOG_INFO': 'n', 'FEATURE_IPV6': 'y',
    'UNICODE_SUPPORT': 'n', 'FEATURE_EDITING': 'n', 'LOCALE_SUPPORT': 'n',
    'FEATURE_HWIB': 'n', 'FEATURE_USE_SENDFILE': 'n', 'FEATURE_SH_EMBEDDED_SCRIPTS': 'n',
    'BUSYBOX_EXEC_PATH': '/proc/self/exe', 'CROSS_COMPILER_PREFIX': '',
    'FEATURE_SEAMLESS_XZ': 'n', 'FEATURE_SEAMLESS_LZMA': 'n', 'FEATURE_SEAMLESS_BZ2': 'n',
    'FEATURE_SEAMLESS_GZ': 'y', 'FEATURE_SEAMLESS_Z': 'n',
    'FEATURE_TAR_SELINUX': 'n', 'FEATURE_TAR_UNAME_GNAME': 'n',
    'FEATURE_FIND_SELINUX': 'n', 'FEATURE_FIND_CONTEXT': 'n',
    'FEATURE_LS_USERNAME': 'n', 'FEATURE_FIND_USER': 'n', 'FEATURE_FIND_GROUP': 'n',
    'FEATURE_PS_LONG': 'n', 'FEATURE_NC_SERVER': 'y', 'NC_EXTRA': 'n',
    'PLATFORM_LINUX': 'y', 'FEATURE_HAVE_RPC': 'n', 'DEBUG': 'n', 'WERROR': 'n',
    'FEATURE_AWK_LIBM': 'y', 'FEATURE_AWK_GNU_EXTENSIONS': 'y',
    'FEATURE_DATE_ISOFMT': 'y', 'FEATURE_DATE_NANO': 'n', 'FEATURE_DATE_COMPAT': 'n',
    'MONOTONIC_SYSCALL': 'y', 'FEATURE_CLEAN_UP': 'n',
    'SH_IS_NONE': 'y', 'SH_IS_ASH': 'n', 'SH_IS_HUSH': 'n',
    'MODPROBE_SMALL': 'n', 'FEATURE_SYNC_FANCY': 'n',  # no syncfs() in bionic android-9
    'BASH_IS_NONE': 'y', 'BASH_IS_ASH': 'n', 'BASH_IS_HUSH': 'n',
}


def main():
    os.environ['srctree'] = os.path.abspath(SRC)
    os.environ.setdefault('KCONFIG_STRICT', '')
    cwd = os.getcwd()
    os.chdir(SRC)
    k = kconfiglib.Kconfig('Config.in', warn=False)
    applets_h = open('include/applets.h').read()
    applet_syms = set()
    for line in applets_h.splitlines():
        if 'APPLET' in line:
            applet_syms.update(n for n in re.findall(r'IF_([A-Z0-9_]+)\(', line)
                               if not n.startswith('NOT_'))
    for name in sorted(applet_syms):
        if name in k.syms:
            k.syms[name].set_value(2 if name in APPLETS else 0)
    for name, v in OVERRIDES.items():
        if name not in k.syms:
            continue
        s = k.syms[name]
        if s.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            s.set_value(2 if v == 'y' else 0)
        else:
            s.set_value(v)
    missing = [a for a in APPLETS if a not in k.syms or k.syms[a].tri_value != 2]
    if missing:
        print('applets not enabled (unknown or dependency):', missing)
    k.write_config('.config')
    lines = ['/* Automatically generated by xt550 configure.py from .config */',
             '#define AUTOCONF_TIMESTAMP "xt550"', '']
    for s in k.unique_defined_syms:
        if s.type == kconfiglib.UNKNOWN:
            continue
        n = s.name
        on = False
        if s.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
            on = s.tri_value == 2
            if on:
                lines.append('#define CONFIG_%s 1' % n)
                lines.append('#define ENABLE_%s 1' % n)
                lines.append('#ifdef MAKE_SUID')
                lines.append('# define IF_%s(...) __VA_ARGS__ "CONFIG_%s"' % (n, n))
                lines.append('#else')
                lines.append('# define IF_%s(...) __VA_ARGS__' % n)
                lines.append('#endif')
                lines.append('#define IF_NOT_%s(...)' % n)
            else:
                lines.append('#undef CONFIG_%s' % n)
                lines.append('#define ENABLE_%s 0' % n)
                lines.append('#define IF_%s(...)' % n)
                lines.append('#define IF_NOT_%s(...) __VA_ARGS__' % n)
        else:
            val = s.str_value
            if s.type == kconfiglib.STRING:
                val = '"%s"' % val.replace('\\', '\\\\').replace('"', '\\"')
            elif val == '':
                continue
            lines.append('#define CONFIG_%s %s' % (n, val))
            lines.append('#define ENABLE_%s 1' % n)
            lines.append('#ifdef MAKE_SUID')
            lines.append('# define IF_%s(...) __VA_ARGS__ "CONFIG_%s"' % (n, n))
            lines.append('#else')
            lines.append('# define IF_%s(...) __VA_ARGS__' % n)
            lines.append('#endif')
            lines.append('#define IF_NOT_%s(...)' % n)
        lines.append('')
    open('include/autoconf.h', 'w', newline='\n').write('\n'.join(lines) + '\n')
    on = sorted(s.name for s in k.unique_defined_syms
                if s.type in (kconfiglib.BOOL, kconfiglib.TRISTATE) and s.tri_value == 2)
    print(len(on), 'options on;', len([a for a in APPLETS if a not in missing]), 'applets')
    os.chdir(cwd)


if __name__ == '__main__':
    main()
